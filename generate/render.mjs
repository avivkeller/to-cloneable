// keep: path -> brand, a member that throws unless `this` is a real instance
// ("x" a getter, "x()" a method, "" for none). walks: own properties the clone
// of a kept class recurses into.
export function renderEntry(table) {
  return `// GENERATED by generate/index.mjs. Do not edit.
import { create } from './core.js';

export const toCloneable = create(${JSON.stringify(table, null, 2)});
`;
}

const labels = {
  inferred: 'Kept unobserved (engine source and spec agree)',
  unverified: 'Spec says cloneable, dropped (no instance, not in engine source)',
  'spec-but-throws': 'Spec says cloneable, throws',
  'spec-but-plain': 'Spec says cloneable, degrades to a plain object',
  'clones-beyond-spec': 'Clones without `[Serializable]`',
  'dropped-for-others': 'Dropped, clones only in the runtime named',
};

export function renderNotes(target, runtimes, idl, findings) {
  const versions = Object.entries(runtimes).map(([name, { version }]) => `${name} ${version}`);
  const refs = [...Object.values(runtimes).flatMap(({ source }) => (source ? [source.ref] : [])), idl.ref];
  const lines = [`### ${target} (${versions.join(', ')})`, ''];
  const multiple = Object.keys(runtimes).length > 1;
  for (const [kind, label] of Object.entries(labels)) {
    const byPath = new Map();
    for (const finding of findings) {
      if (finding.kind === kind) byPath.set(finding.path, [...(byPath.get(finding.path) ?? []), finding.runtime]);
    }
    if (byPath.size === 0) continue;
    const items = [...byPath.keys()].sort().map((path) => {
      const where = byPath.get(path);
      return multiple && where.length < versions.length ? `\`${path}\` (${where.join(', ')})` : `\`${path}\``;
    });
    lines.push(`- **${label}:** ${items.join(', ')}`);
  }
  if (lines.length === 2) lines.push('- Nothing inferred, no disagreements.');
  lines.push(`- Sources: ${refs.map((ref) => `\`${ref}\``).join(', ')}`, '');
  return lines.join('\n');
}
